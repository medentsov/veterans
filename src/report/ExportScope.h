/// Область экспорта и печати (M7-02).
///
/// Один и тот же выбор используется для Excel, PDF и печати, чтобы «что вижу,
/// то и выгружаю» работало одинаково во всех форматах.
enum class ExportScope {
    Checked,   ///< только отмеченные галочками записи
    All,       ///< все записи, независимо от фильтра
    Filtered,  ///< текущий результат быстрого поиска и расширенного фильтра
};
